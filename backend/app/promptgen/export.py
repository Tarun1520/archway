"""
Exporting the plan: one JSON file of everything, one readable Markdown file, and the pack as a zip.

    plan_json(...)      the full plan as data: brief, research, decisions, options, roadmap, prompts, links
    plan_markdown(...)  the same plan as one document a person can read top to bottom
    pack_zip(...)       build-pack/ (every pack file) plus plan.json and PLAN.md, as zip bytes

Labelled, never dressed up
    The export says which option version it is for, whether every rubric line passed (or which did not), and
    whether the decision model and the language model ran live or from fixtures. A partial plan says PARTIAL.

How it plugs in
    The `export` graph node builds the JSON from the run's state (pure: no database). app/api/plan.py turns the
    saved plan into the downloads.
"""

import io
import json
import zipfile
from typing import Any

from app.models.common import utc_now
from app.models.plan import PlanSnapshot
from app.options.material import latest_by_id, verdicts_by_component
from app.options.versions import presented


def service_modes(context: Any) -> dict[str, str | None]:
    """Which mode ("live" or "fixture") each outside service of this run is in, from the run context."""
    integrations = getattr(context, "integrations", None)
    github = getattr(getattr(integrations, "github", None), "mode", None)
    return {"language model": context.llm.mode, "decisions": getattr(context.decisions, "mode", None), "github": github}


def fixture_names(services: dict[str, str | None]) -> list[str]:
    return sorted(name for name, mode in services.items() if mode == "fixture")


def plan_json(state: dict[str, Any], plan: PlanSnapshot, services: dict[str, str | None] | None = None) -> dict[str, Any]:
    """The whole plan as data. `services` names the mode ("live" or "fixture") each outside service ran in."""
    brief = state.get("brief") or {}
    verdicts = verdicts_by_component(state.get("eligibility", []))
    modes = sorted({r.get("jev_mode") for r in state.get("receipts", []) if r.get("jev_mode")})
    engines = sorted({r.get("jev_model_id") for r in state.get("receipts", []) if r.get("jev_model_id")})
    return {
        "generated_at": utc_now().isoformat(),
        "generated_by": "Archway",
        "architecture": plan.built_for.model_dump() if plan.built_for else None,
        "outcome": plan.outcome,
        "rubric_passed": plan.passed,
        "notes": plan.notes,
        "decision_engine": {"modes": modes, "engines": engines},
        "services": services or {},
        "fixture_services": fixture_names(services or {}),
        "brief": brief,
        "research": {
            "capabilities": [{"id": c["id"], "name": c["name"], "need": c.get("need")} for c in state.get("capabilities", [])],
            "components": [
                {"id": c["id"], "name": c["name"], "capability_id": c.get("capability_id"),
                 "repo": (c.get("facts") or {}).get("reference"), "license": (c.get("facts") or {}).get("license"),
                 "eligibility": verdicts.get(c["id"], {}).get("status"), "reasons": verdicts.get(c["id"], {}).get("reasons", []),
                 "decided_by": verdicts.get(c["id"], {}).get("decided_by"),
                 "evidence_ids": (c.get("facts") or {}).get("evidence_ids", [])}
                for c in latest_by_id(state.get("components", []))
            ],
            "evidence": [{"id": e["id"], "url": e.get("url"), "source_type": e.get("source_type")} for e in state.get("evidence", [])],
            "notes": state.get("research_notes", []),
        },
        "decision_receipts": [
            {key: r.get(key) for key in ("id", "candidate_id", "requirement_id", "question_type", "jev_mode", "jev_model_id", "final_result", "needs_review", "evidence_ids")}
            for r in state.get("receipts", [])
        ],
        "options": presented(state.get("options", [])),
        "roadmap": plan.roadmap.model_dump(mode="json") if plan.roadmap else None,
        "prompts": [
            {"path": f.path, "task_ids": f.task_ids, "prerequisites": f.prerequisites,
             "rubric": [r.model_dump() for r in f.rubric]}
            for f in plan.files if f.kind == "prompt"
        ],
        "links": [link.model_dump() for link in plan.links],
    }


def plan_markdown(data: dict[str, Any]) -> str:
    """The plan as one document. Built from plan_json's output, so both always say the same."""
    architecture = data.get("architecture") or {}
    lines = [
        f"# Plan for {architecture.get('id', '?')} version {architecture.get('version', '?')}",
        "",
        f"Generated by Archway on {data['generated_at'][:10]}. Outcome: **{(data.get('outcome') or 'unknown').upper()}**"
        + (" (every rubric line passed)." if data.get("rubric_passed") else " (some rubric lines did not pass: see below)."),
        "",
        f"Decision engine: {', '.join(data['decision_engine']['engines']) or 'not reported'}"
        f" ({', '.join(data['decision_engine']['modes']) or 'no decisions'}).",
        "",
    ]
    if data.get("fixture_services"):
        lines += [
            f"**FIXTURE MODE: {', '.join(data['fixture_services'])} answered from recorded fixtures, not live services.** "
            "This plan shows how Archway works; it is not a real recommendation.",
            "",
        ]
    lines += [
        "## Brief",
        "",
        f"Problem: {(data.get('brief') or {}).get('problem') or 'Not stated'}",
        "",
    ]
    for requirement in (data.get("brief") or {}).get("must_have", []):
        lines.append(f"- {requirement['id']}: {requirement['text']}")
    lines += ["", "## Source-to-decision links", ""]
    for link in data.get("links", []):
        lines.append(f"### {link['requirement_id']}: {link['requirement']}")
        lines.append(f"Coverage: {link['coverage']}. Tasks: {', '.join(link['task_ids']) or 'none'}.")
        for component in link["components"]:
            if component["kind"] == "reuse":
                evidence = ", ".join(f"{e['id']} ({e['url'] or 'no address'})" for e in component["evidence"]) or "none"
                lines.append(
                    f"- {component['name']} reuses {component['repo']}: eligibility {component['eligibility']}"
                    f" (decided by {component['decided_by']}); receipts {', '.join(component['receipt_ids']) or 'none'}; evidence {evidence}"
                )
            else:
                lines.append(f"- {component['name']}: built (no outside source)")
        lines.append("")
    roadmap = data.get("roadmap") or {}
    lines += ["## Roadmap", ""]
    for task in roadmap.get("tasks", []):
        lines.append(f"- {task['id']} {task['title']} ({task['stage']}; after {', '.join(task['prerequisites']) or 'nothing'})")
    lines += ["", "## Decisions", ""]
    for decision in roadmap.get("decisions", []):
        lines.append(f"- {decision['id']} {decision['title']}: {decision['decision']}")
    lines += ["", "## Prompt checks", ""]
    for prompt in data.get("prompts", []):
        failed = [r for r in prompt["rubric"] if not r["passed"]]
        lines.append(f"- {prompt['path']}: " + ("all 8 checks passed" if not failed else "FAILED " + "; ".join(f"{r['criterion']} ({r['detail']})" for r in failed)))
    if data.get("notes"):
        lines += ["", "## Notes", ""] + [f"- {note}" for note in data["notes"]]
    lines += ["", "Generated code requires human review before use.", ""]
    return "\n".join(lines)


def pack_zip(plan: PlanSnapshot, data: dict[str, Any]) -> bytes:
    """build-pack/ with every file, plus plan.json and PLAN.md, as the bytes of a zip file."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for file in plan.files:
            archive.writestr(f"build-pack/{file.path}", file.content)
        archive.writestr("build-pack/plan.json", json.dumps(data, indent=2, ensure_ascii=False, default=str))
        archive.writestr("build-pack/PLAN.md", plan_markdown(data))
    return buffer.getvalue()
